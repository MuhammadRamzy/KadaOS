def _fullname():
    import pwd
    return (pwd.getpwuid(os.getuid()).pw_gecos.split(",")[0] or os.environ.get("USER", "")).strip() or os.environ.get("USER", "")

def _initials():
    import pwd
    name = (pwd.getpwuid(os.getuid()).pw_gecos.split(",")[0] or os.environ.get("USER", "?")).split()
    return ("".join(w[0] for w in name[:2]).upper() or "?")

def _mono_font(size):
    from PIL import ImageFont
    f = ImageFont.truetype(str(Path.home() / ".local/share/fonts/AdwaitaFonts/AdwaitaSans-Regular.ttf"), size)
    try: f.set_variation_by_axes([700])
    except Exception: pass
    return f

def avatar():
    """Round monogram: radial accent->violet gradient, top sheen, inset ring, soft letters."""
    out = Path.home() / ".local/share/myos/avatar.png"; face = Path.home() / ".face"
    try:
        import numpy as np
        from PIL import Image, ImageDraw, ImageFilter
        out.parent.mkdir(parents=True, exist_ok=True)
        if face.exists():
            im = Image.open(face).convert("RGBA").resize((512, 512))
            m = Image.new("L", (512, 512)); ImageDraw.Draw(m).ellipse((0, 0, 511, 511), fill=255)
            im.putalpha(m); im.save(out); return out
        N = 512; cx, cy = N * 0.40, N * 0.34
        yy, xx = np.mgrid[0:N, 0:N].astype(np.float32)
        r = np.clip(np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / (N * 0.80), 0, 1)[..., None]
        acc = np.array(rgb(P["accent"]), np.float32)
        vio = np.array([0x6a, 0x47, 0xd6], np.float32)    # deep indigo-violet edge for contrast
        col = acc * (1 - r) + vio * r
        img = np.concatenate([col, np.full((N, N, 1), 255, np.float32)], 2)
        base = Image.fromarray(np.clip(img, 0, 255).astype("uint8"), "RGBA")
        disc = Image.new("L", (N, N)); ImageDraw.Draw(disc).ellipse((0, 0, N - 1, N - 1), fill=255)
        base.putalpha(disc)
        d = ImageDraw.Draw(base)
        d.ellipse((6, 6, N - 7, N - 7), outline=(255, 255, 255, 46), width=2)   # inset ring
        txt = Image.new("RGBA", (N, N), (0, 0, 0, 0)); td = ImageDraw.Draw(txt)
        s2 = _initials(); font = _mono_font(236)
        bb = td.textbbox((0, 0), s2, font=font)
        pos = ((N - bb[2] - bb[0]) / 2, (N - bb[3] - bb[1]) / 2 - 8)
        sh = Image.new("RGBA", (N, N), (0, 0, 0, 0)); ImageDraw.Draw(sh).text(pos, s2, font=font, fill=(0, 0, 0, 90))
        sh = sh.filter(ImageFilter.GaussianBlur(6))
        base.alpha_composite(sh); td.text(pos, s2, font=font, fill=(255, 255, 255, 240))
        base.alpha_composite(txt); base.save(out)
    except Exception as e:
        print("avatar skipped:", e)
    return out

