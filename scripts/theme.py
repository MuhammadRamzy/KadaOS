def qt_roles(text, fade):
    # QPalette order: WindowText Button Light Midlight Dark Mid Text BrightText ButtonText Base Window Shadow
    #                 Highlight HighlightedText Link LinkVisited AlternateBase NoRole ToolTipBase ToolTipText Placeholder Accent
    return ", ".join([text, P["surface2"], "#4a4a52", P["border"], P["bg0"], P["surface"], text, "#ffffff", text,
                      P["bg0"], P["bg"], "#000000", P["accent"] if not fade else P["surface2"], P["bg0"] if not fade else P["dim"],
                      P["accent_hi"], P["violet"], P["surface"], P["bg"], P["surface2"], P["text"], P["dim"], P["accent"]])
